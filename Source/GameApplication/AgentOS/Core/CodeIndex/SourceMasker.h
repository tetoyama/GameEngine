// =======================================================================
//
// SourceMasker.h
//
// C++ソースの「コメント・文字列・文字リテラル・生文字列」の中身を
// 空白へ潰した写しを作る前処理。
//
// 目的は波括弧カウントの安全化。素の正規表現でC++を切ろうとすると、
//   const char* s = "){";
//   // ここで } と書いてもコードではない
// のようなリテラル／コメント中の括弧を数えてしまい、
// 関数やクラスの範囲が壊れる。先にそれらを潰しておけば、
// 以降の深度追跡は単純な { } の勘定で足りる。
//
// 出力は入力と「同じ長さ・同じ改行位置」を保つ。したがって
// マスク後のオフセットや行番号を、そのまま原文に適用できる。
//
// =======================================================================
#pragma once

#include <string>

namespace agentos {

// コメント／各種リテラルの中身を空白へ置換した写しを返す。
// 改行は保存されるため、行数・行番号は原文と一致する。
std::string MaskLiteralsAndComments(const std::string& source);

} // namespace agentos
